    public function __construct(private IslandRepository $islandRepository) {}

    public function detectFromCoordinates(float $lat, float $lng): ?Island
    {
        foreach (self::ISLAND_BOUNDS as $islandName => $bounds) {
            [$swlat, $swlng, $nelat, $nelng] = $bounds;
            if ($lat >= $swlat && $lat <= $nelat && $lng >= $swlng && $lng <= $nelng) {
                return $this->islandRepository->findOneBy(['name' => $islandName]);
            }
        }
        return null;
    }
